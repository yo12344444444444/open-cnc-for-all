/** Questions belonging to a lesson: keyword match on question text, else whole topic. */
export function lessonQuestions(lesson, list) {
  const kwHits = list.filter((q) => lesson.kw.some((k) => q.q.includes(k)));
  if (kwHits.length >= 8) return kwHits;
  return [...kwHits, ...list.filter((q) => q.t === lesson.topic && !kwHits.includes(q))];
}

/** Best lesson for a question (for the "related lesson" link after a mistake). */
export function lessonFor(q) {
  let best = null;
  let score = 0;
  for (const l of LESSONS) {
    const s = l.kw.reduce((n, k) => n + (q.q.includes(k) ? 1 : 0), 0) + (l.topic === q.t ? 0.5 : 0);
    if (s > score) {
      score = s;
      best = l;
    }
  }
  if (score >= 1) return best;
  return LESSONS.find((l) => l.id === q.t) ?? LESSONS.find((l) => l.topic === q.t && l.id !== 'basics') ?? null;
}
